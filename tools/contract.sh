#!/usr/bin/env bash
# contract.sh -- the recorded contract run (T6): clean fleet check without (leg A) and with (leg B) the byo SDK,
# then every oracle with a command; writes docs/publish/contract.md (hashes and pass lines only, no game bytes).
#
#   bash tools/contract.sh [--sdk <dir>]     run the legs + oracles, write the record; exit 1 on any RED
#   bash tools/contract.sh --check-record    exit 0 iff the record is all green and its src/config stamp = HEAD
#
# Leg A: tools/psyq/ must be absent. Leg B (--sdk only): <dir> copied to tools/psyq/ (firewall-purged, removed on
# any exit); SHA1s must equal config/check.<alias>.sha and leg A. Refuses a dirty src/ or config/. Never git clean.
# Env: PY (default python3). Logs: .run/contract/<step>.log. Takes ~20 min.
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT" || exit 2
PY="${PY:-python3}"
REC=docs/publish/contract.md
LOGS=.run/contract
stamp() { echo "src=$(git rev-parse HEAD:src) config=$(git rev-parse HEAD:config)"; }

case "${1:-}" in
  -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  --check-record)
    [ -f "$REC" ] || { echo "contract: no record $REC"; exit 1; }
    grep -qE '^contract: ([0-9]+) of \1, oracles ([0-9]+) of \2 green$' "$REC" || { echo "contract: record not all green"; exit 1; }
    ! grep -q 'RED' "$REC" || { echo "contract: record has a RED line"; exit 1; }
    grep -qxF -- "- stamp: \`$(stamp)\`" "$REC" || { echo "contract: record stamp != HEAD src/config"; exit 1; }
    echo "contract: record OK"; exit 0 ;;
esac
SDK=""
while [ $# -gt 0 ]; do
  case "$1" in
    --sdk) SDK="${2:-}"; [ -d "$SDK" ] || { echo "contract: --sdk needs a directory"; exit 2; }; shift 2 ;;
    *) echo "contract: unknown argument $1 (see --help)"; exit 2 ;;
  esac
done
[ -z "$(git status --porcelain -- src config)" ] || { echo "contract: src/ or config/ dirty; commit first"; exit 2; }
[ ! -e tools/psyq ] || { echo "contract: tools/psyq/ present; leg A needs it absent"; exit 2; }
trap 'rm -rf tools/psyq' EXIT
mkdir -p "$LOGS" docs/publish
OUT=(); RED=0; legs=0; legs_ok=0; ora=0; ora_ok=0
rec() { OUT+=("$1"); echo "$1"; }
ALIASES=(slus rockx5)
declare -A SHA_A

# leg <A|B>: make clean + make check; pass line + per-binary SHA1 vs config (and vs leg A for B).
leg() {
  local L=$1 ok=1 a want file got line
  legs=$((legs+1))
  make clean >"$LOGS/leg$L.clean.log" 2>&1
  make check PY="$PY" >"$LOGS/leg$L.check.log" 2>&1
  line=$(grep -m1 -E '^check: [0-9]+ of [0-9]+ green, [0-9]+ failed$' "$LOGS/leg$L.check.log")
  if [ "$line" = "check: 2 of 2 green, 0 failed" ]; then rec "- \`make clean && make check PY=PY\` → \`$line\`"
  else ok=0; rec "- RED: \`make clean && make check PY=PY\` → \`${line:-no check line}\` ($LOGS/leg$L.check.log)"; fi
  for a in "${ALIASES[@]}"; do
    read -r want file < "config/check.$a.sha"
    got=$(sha1sum "$file" 2>/dev/null | cut -d' ' -f1)
    if [ "$got" = "$want" ] && { [ "$L" = A ] || [ "$got" = "${SHA_A[$a]:-}" ]; }; then
      rec "- $a: sha1 \`$got\` = config/check.$a.sha${SHA_A[$a]:+ = leg A}"
    else ok=0; rec "- RED: $a: sha1 \`${got:-missing}\`, config \`$want\`${SHA_A[$a]:+, leg A \`${SHA_A[$a]}\`}"; fi
    [ "$L" = A ] && SHA_A[$a]=$got
  done
  [ $ok = 1 ] && legs_ok=$((legs_ok+1)) || RED=1
}

# oracle <name> <pass-regex> <cmd...>: run, record the matching pass lines (all regexes in $2 joined by '@@' must hit).
oracle() {
  local n=$1 pats=$2 shown=$3; shift 3
  local log="$LOGS/oracle.$n.log" rc lines p ok=1
  ora=$((ora+1))
  "$@" >"$log" 2>&1; rc=$?
  lines=""
  mapfile -t P < <(printf '%s\n' "${pats//@@/$'\n'}")
  for p in "${P[@]}"; do
    l=$(grep -m1 -E "$p" "$log") || { ok=0; continue; }
    lines="${lines:+$lines · }\`$l\`"
  done
  [ $rc -eq 0 ] || ok=0
  if [ $ok = 1 ]; then ora_ok=$((ora_ok+1)); rec "- \`$shown\` → $lines"
  else RED=1; rec "- RED: \`$shown\` → exit $rc ${lines:-no pass line} ($log)"; fi
}

H_DATE=$(git log -1 --format=%cs); H_SUBJ=$(git log -1 --format=%s)
rec "# Contract record"
rec "<!-- generated by tools/contract.sh; do not hand-edit. Hashes and pass lines only. -->"
rec "- date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
rec "- head: $H_DATE $H_SUBJ"
rec "- stamp: \`$(stamp)\`"
if [ -n "$SDK" ]; then rec "- sdk: a byo path was given"; else rec "- sdk: none given"; fi  # never the path
rec ""
rec "## Leg A: without the SDK (tools/psyq/ absent, asserted)"
leg A
rec ""
rec "## Leg B: with the byo SDK at tools/psyq/"
if [ -n "$SDK" ]; then
  cp -a "$SDK" tools/psyq || { echo "contract: cannot copy SDK"; exit 2; }
  leg B
  rm -rf tools/psyq
else rec "leg B: not run: no byo SDK"; fi
rec ""
rec "## Oracles"
oracle loadmap '^controls: [0-9]+ passed, 0 failed$' "PY tools/loadmap/loadmap.py check" "$PY" tools/loadmap/loadmap.py check
oracle boundaries '^boundaries: 0 phantoms, 0 truncations$' "PY tools/census/boundaries.py" "$PY" tools/census/boundaries.py
oracle tools-health-full '^harness: ([5-9]|[1-9][0-9]+) pairs, 0 disagreements$@@^tools-health: OK$' \
  "make tools-health-full PY=PY" make tools-health-full PY="$PY"
oracle firewall-check '^firewall-check: OK \(control caught, tree clean\)$' "make firewall-check PY=PY" make firewall-check PY="$PY"
oracle redux-smoke '^redux: lua ok ?$' "bash tools/redux/run.sh tools/redux/smoke.lua" env PY="$PY" bash tools/redux/run.sh tools/redux/smoke.lua
rec ""
rec "## Oracles without a command here"
rec "- Ghidra import (\`bash tools/ghidra/import.sh\`): ~320 s; its output docs/oracle/boundaries.txt is what boundaries.py checks."
rec "- Load-address proof (\`PY tools/loadmap/prove.py\`): regenerates the tracked docs/memory-map.md."
rec ""
[ $RED = 0 ] && G=" green" || G=" RED"
rec "contract: $legs_ok of $legs, oracles $ora_ok of $ora$G"
printf '%s\n' "${OUT[@]}" > "$REC"
exit $RED
