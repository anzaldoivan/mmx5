#!/usr/bin/env python3
"""symptoms.py — the symptom index: diff symptom -> cookbook idiom entries -> levers.

  build            write docs/codegen-map/SYMPTOMS.md (sorted, deterministic) from the idiom entries.
  check            every idiom entry has `symptom:`/`lever:` lines and is indexed; every levers.yaml id is
                   indexed; every row's entry/lever ids resolve, each lever's `cookbook:` names its entry;
                   every cookbook/C0002.md Entries id resolves; C0002 has no TODO; SYMPTOMS.md is fresh.
                   Prints `symptoms: FAIL <what>` per failure, then `symptoms: <n> of <n> idiom entries indexed,
                   <m> of <m> levers indexed, <u> unindexed, <r> unresolved`; exit 1 on any failure.
  --selftest       scratch copy under .run/codegen/symptoms-selftest/ with a planted idiom entry absent
                   from SYMPTOMS.md; check must refuse it as unindexed. ROM-free.

Inputs: cookbook/INDEX.md (tag `idiom`, not `cookbook-format`), each entry's column-0 `symptom: <phrase>` and
`lever: <id>` lines, docs/codegen-map/levers.yaml (JSON list: id, cookbook), cookbook/C0002.md table Entries cells.
"""
import argparse
import contextlib
import io
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = "docs/codegen-map/SYMPTOMS.md"
HEADER = "<!-- generated by tools/codegen/symptoms.py build; never hand-edit -->\n"


def entries(root):
    """-> {id: (symptoms, levers)} for idiom entries in cookbook/INDEX.md."""
    out = {}
    for line in (root / "cookbook/INDEX.md").read_text().splitlines():
        f = [x.strip() for x in line.split("|")]
        if len(f) < 3 or not re.fullmatch(r"C\d{4}", f[0]):
            continue
        tags = f[2].split(",")
        if "idiom" not in tags or "cookbook-format" in tags:
            continue
        p = root / "cookbook" / f"{f[0]}.md"
        text = p.read_text() if p.exists() else ""
        out[f[0]] = (re.findall(r"^symptom: (.+?)\s*$", text, re.M), re.findall(r"^lever: (\S+)", text, re.M))
    return out


def render(root):
    rows = {}
    for eid, (syms, levs) in entries(root).items():
        for s in syms:
            e, lv = rows.setdefault(s, (set(), set()))
            e.add(eid)
            lv.update(levs)
    body = "".join(f"| {s.replace('|', chr(92) + '|')} | {', '.join(sorted(e))} | {', '.join(sorted(lv))} |\n"
                   for s, (e, lv) in sorted(rows.items()))
    return HEADER + "\n# Symptom index\n\n| symptom | entries | levers |\n|---|---|---|\n" + body


def parse_rows(text):
    """-> [(entry ids, lever ids)] from SYMPTOMS.md table rows."""
    rows = []
    for line in text.splitlines():
        m = re.fullmatch(r"\| (.*) \| ([^|]*) \| ([^|]*) \|", line)
        if m and m[1] not in ("symptom",):
            rows.append(([x for x in m[2].split(", ") if x], [x for x in m[3].split(", ") if x]))
    return rows


def check(root=ROOT):
    fails = []
    ents = entries(root)
    levers = {r["id"]: r.get("cookbook") for r in json.loads((root / "docs/codegen-map/levers.yaml").read_text())}
    p = root / OUT
    text = p.read_text() if p.exists() else ""
    rows = parse_rows(text)
    row_e = {e for es, _ in rows for e in es}
    row_l = {lv for _, ls in rows for lv in ls}
    unidx = unres = 0
    for eid, (syms, levs) in sorted(ents.items()):
        if not syms or not levs:
            fails.append(f"{eid} lacks symptom/lever line")
        if eid not in row_e:
            unidx += 1
            fails.append(f"unindexed entry {eid}")
    for lid in sorted(levers):
        if lid not in row_l:
            unidx += 1
            fails.append(f"unindexed lever {lid}")
    for es, ls in rows:
        for e in es:
            if not (root / "cookbook" / f"{e}.md").exists():
                unres += 1
                fails.append(f"unresolved entry {e}")
        for lv in ls:
            if lv not in levers:
                unres += 1
                fails.append(f"unresolved lever {lv}")
            elif levers[lv] not in es:
                unres += 1
                fails.append(f"lever {lv} cookbook {levers[lv]} not in row {', '.join(es)}")
    c2 = (root / "cookbook/C0002.md").read_text()
    for line in c2.splitlines():
        cells = [x.strip() for x in line.strip().strip("|").split("|")]
        if line.startswith("|") and len(cells) >= 4:
            for e in re.findall(r"C\d{4}", cells[-1]):
                if not (root / "cookbook" / f"{e}.md").exists():
                    unres += 1
                    fails.append(f"unresolved C0002 entry {e}")
    if "TODO" in c2:
        fails.append(f"C0002 has {c2.count('TODO')} TODO")
    if text != render(root):
        fails.append("stale SYMPTOMS.md")
    for f in fails:
        print(f"symptoms: FAIL {f}")
    n, m = len(ents), len(levers)
    print(f"symptoms: {len(set(ents) & row_e)} of {n} idiom entries indexed, {len(set(levers) & row_l)} of {m} "
          f"levers indexed, {unidx} unindexed, {unres} unresolved")
    return 1 if fails else 0


def selftest():
    s = ROOT / ".run/codegen/symptoms-selftest"
    shutil.rmtree(s, ignore_errors=True)
    for rel in ("cookbook/INDEX.md", "cookbook/C0002.md", "docs/codegen-map/levers.yaml", OUT):
        (s / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(ROOT / rel, s / rel)
    for e in entries(ROOT):
        shutil.copy(ROOT / "cookbook" / f"{e}.md", s / "cookbook" / f"{e}.md")
    for e in set(re.findall(r"C\d{4}", (ROOT / "cookbook/C0002.md").read_text())):
        if (ROOT / "cookbook" / f"{e}.md").exists():
            shutil.copy(ROOT / "cookbook" / f"{e}.md", s / "cookbook" / f"{e}.md")
    (s / "cookbook/C9999.md").write_text("# C9999 — planted\nsymptom: planted symptom\nlever: planted_lever\n")
    with open(s / "cookbook/INDEX.md", "a") as f:
        f.write("C9999 | planted | idiom,planted | - | - | selftest\n")
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        rc = check(s)
    if rc == 1 and "symptoms: FAIL unindexed entry C9999" in buf.getvalue():
        print("symptoms: control OK -- unindexed entry refused")
        return 0
    print("symptoms: control FAILED -- planted entry not refused\n" + buf.getvalue())
    return 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", choices=["build", "check"])
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.cmd == "build":
        (ROOT / OUT).write_text(render(ROOT))
        print(f"symptoms: wrote {OUT}")
        return 0
    if a.cmd == "check":
        return check()
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
