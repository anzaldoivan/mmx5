#!/usr/bin/env python3
"""progress.py — publish the decompilation progress numbers, generated, with a freshness stamp (G58).

  progress.py write       census outputs (.run/census/report.txt, inventory.jsonl) -> README.md block between
                          `<!-- progress:begin -->`/`<!-- progress:end -->` and docs/progress.json (shields endpoint).
  progress.py check       exit 1 when the README stamp's `HEAD:src`/`HEAD:config` tree ids differ from the current ones,
                          when docs/progress.json disagrees with the README numbers, or (census report present)
                          when regeneration differs ignoring the date; else `progress: OK`. Game-free (CI runs it).
  progress.py --selftest  fixture under .run/progress/selftest: a fresh write passes check, a stale stamp fails
                          -> `progress: control OK`.

Fleet numbers come from the census line `census: stubs N of T game functions (C c, L ledgered); vendor V asm`
(tools/census/census.py), per-binary ones from inventory.jsonl (kind "game", status "c"|"asm"). Counts only.
Stdlib only; runs under `python -S`.
"""
import datetime
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BEGIN, END = "<!-- progress:begin -->", "<!-- progress:end -->"
CMD = "PY tools/progress/progress.py write"
STUBS = re.compile(r"^census: stubs (\d+) of (\d+) game functions \((\d+) c, (\d+) ledgered\); vendor (\d+) asm$", re.M)
FLEET = re.compile(r"^\*\*Progress:\*\* (\d+) of (\d+) game functions in C ", re.M)
STAMP = re.compile(r"stamp: src `([0-9a-f]+)`, config `([0-9a-f]+)`, (\d{4}-\d\d-\d\d) UTC")


def trees():
    out = subprocess.run(["git", "rev-parse", "HEAD:src", "HEAD:config"], cwd=ROOT, capture_output=True, text=True)
    if out.returncode:
        sys.exit(f"progress: git rev-parse HEAD:src HEAD:config failed: {out.stderr.strip()}")
    return out.stdout.split()


def pct(c, t):
    return f"{100 * c / t:.1f}%"


def numbers(census):
    m = STUBS.search((census / "report.txt").read_text(encoding="utf-8"))
    if not m:
        sys.exit(f"progress: no `census: stubs` line in {census / 'report.txt'}")
    _, total, c, ledgered, vendor = map(int, m.groups())
    per = {}
    for line in (census / "inventory.jsonl").read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        if r["kind"] == "game":
            n = per.setdefault(r["alias"], [0, 0])
            n[0] += r["status"] == "c"
            n[1] += 1
    return total, c, ledgered, vendor, per


def message(c, total):
    return f"{c} / {total} functions ({pct(c, total)})"


def render(nums, src, cfg, date):
    total, c, ledgered, vendor, per = nums
    lines = [BEGIN,
             "<!-- generated by tools/progress/progress.py write; never edit; `progress.py check` asserts it fresh -->",
             f"**Progress:** {c} of {total} game functions in C ({pct(c, total)}); {ledgered} ledgered; "
             f"vendor {vendor} asm.", ""]
    lines += [f"- {a}: {pc} of {pt} game functions in C ({pct(pc, pt)})" for a, (pc, pt) in sorted(per.items())]
    lines += ["", f"<sub>stamp: src `{src}`, config `{cfg}`, {date} UTC; `{CMD}`</sub>", END]
    js = {"schemaVersion": 1, "label": "decompiled", "message": message(c, total), "color": "blue"}
    return "\n".join(lines), json.dumps(js, indent=2) + "\n"


def splice(readme, block):
    text = readme.read_text(encoding="utf-8")
    i, j = text.index(BEGIN), text.index(END) + len(END)
    return text[:i] + block + text[j:]


def write(readme, jpath, census):
    src, cfg = trees()
    block, js = render(numbers(census), src, cfg, datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d"))
    readme.write_text(splice(readme, block), encoding="utf-8", newline="\n")
    jpath.parent.mkdir(parents=True, exist_ok=True)
    jpath.write_text(js, encoding="utf-8", newline="\n")
    print(f"progress: wrote {readme.name} block and {jpath.name}: {json.loads(js)['message']}")


def check(readme, jpath, census):
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        return f"no {BEGIN} ... {END} block in {readme}"
    block = text[text.index(BEGIN):text.index(END) + len(END)]
    st, fl = STAMP.search(block), FLEET.search(block)
    if not st or not fl:
        return "block has no stamp or no fleet line; rerun write"
    src, cfg = trees()
    if (st[1], st[2]) != (src, cfg):
        return f"stale stamp: block src {st[1][:12]} config {st[2][:12]}, HEAD src {src[:12]} config {cfg[:12]}; rerun write"
    js = json.loads(jpath.read_text(encoding="utf-8"))
    if js.get("message") != message(int(fl[1]), int(fl[2])):
        return f"{jpath.name} message {js.get('message')!r} disagrees with the README numbers"
    if (census / "report.txt").exists():
        rblock, rjs = render(numbers(census), src, cfg, st[3])
        if rblock != block or json.loads(rjs) != js:
            return "census outputs regenerate a different block or json; rerun write"
    return None


def selftest():
    d = ROOT / ".run/progress/selftest"
    shutil.rmtree(d, ignore_errors=True)
    (d / "census").mkdir(parents=True)
    (d / "census/report.txt").write_text(
        "census: stubs 7 of 10 game functions (2 c, 1 ledgered); vendor 3 asm\n", encoding="utf-8")
    rows = [("a", "c"), ("a", "asm"), ("a", "asm"), ("b", "c")] + [("b", "asm")] * 6
    (d / "census/inventory.jsonl").write_text("".join(
        json.dumps({"alias": a, "kind": "game", "status": s}) + "\n" for a, s in rows)
        + json.dumps({"alias": "b", "kind": "libobj", "status": "asm"}) + "\n", encoding="utf-8")
    readme, jpath = d / "README.md", d / "progress.json"
    readme.write_text(f"# x\n\n{BEGIN}\n{END}\n\ntail\n", encoding="utf-8")
    print("selftest: fresh write (must pass)")
    write(readme, jpath, d / "census")
    why = check(readme, jpath, d / "census")
    assert why is None, why
    assert json.loads(jpath.read_text())["message"] == "2 / 10 functions (20.0%)"
    assert "- a: 1 of 3 game functions in C (33.3%)" in readme.read_text() and readme.read_text().endswith("tail\n")
    print("selftest: stale stamp (must fail)")
    readme.write_text(re.sub(r"src `[0-9a-f]+`", "src `" + "0" * 40 + "`", readme.read_text()), encoding="utf-8")
    why = check(readme, jpath, d / "census")
    assert why and why.startswith("stale stamp"), why
    print(f"selftest: caught: {why}")
    print("progress: control OK")


def main():
    mode = sys.argv[1] if len(sys.argv) == 2 else ""
    readme, jpath, census = ROOT / "README.md", ROOT / "docs/progress.json", ROOT / ".run/census"
    if mode == "--selftest":
        selftest()
    elif mode == "write":
        write(readme, jpath, census)
    elif mode == "check":
        why = check(readme, jpath, census)
        if why:
            print(f"progress: FAIL: {why}")
            sys.exit(1)
        print("progress: OK")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
